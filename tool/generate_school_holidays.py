#!/usr/bin/env python3
"""Generates lib/features/holidays/data/school_holiday_data.dart.

Input: tool/school_holidays/y*.txt, one period per line:
    START END DE-XX GROUPS TAGS NAME...
copied from the OpenHolidays API (https://openholidaysapi.org, school
holidays for Germany). Islands-only periods (tag "Exception", e.g. Sylt)
and periods only for vocational schools in Mecklenburg-Vorpommern
(group DE-MV-BBS without DE-MV-ABS) are skipped: the app shows the
general-school holidays of a state.

Run: python3 tool/generate_school_holidays.py && dart format lib/features/holidays/data
"""
import glob
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "lib/features/holidays/data/school_holiday_data.dart")

KINDS = {
    "Winterferien": "winter",
    "Halbjahresferien": "midYear",
    "Halbjahrespause": "midYear",
    "Fastnachtsferien": "carnival",
    "Frühjahrsferien": "spring",
    "Osterferien": "easter",
    "Pfingstferien": "whitsun",
    "Sommerferien": "summer",
    "Herbstferien": "autumn",
    "Weihnachtsferien": "christmas",
}


def main():
    periods = {}
    for path in sorted(glob.glob(os.path.join(ROOT, "tool/school_holidays/y*.txt"))):
        with open(path, encoding="utf-8") as f:
            for raw in f:
                line = raw.strip()
                if not line:
                    continue
                start, end, state, groups, tags, name = line.split(" ", 5)
                if "Exception" in tags:
                    continue
                if groups != "-" and "DE-MV-ABS" not in groups.split(","):
                    continue
                code = state.removeprefix("DE-").lower()
                kind = KINDS.get(name, "dayOff")
                periods.setdefault(code, set()).add((start, end, kind))

    def date(iso):
        y, m, d = (int(x) for x in iso.split("-"))
        return f"LocalDate({y}, {m}, {d})"

    lines = [
        "// GENERATED by tool/generate_school_holidays.py – do not edit by hand.",
        "// Source: OpenHolidays API (openholidaysapi.org), general schools.",
        "",
        "import '../../../core/date/local_date.dart';",
        "import '../domain/entities/german_state.dart';",
        "import '../domain/entities/school_holiday.dart';",
        "",
        "/// School holidays per state, sorted by start date.",
        "const Map<GermanState, List<SchoolHolidayPeriod>> schoolHolidayData = {",
    ]
    for code in sorted(periods):
        lines.append(f"  GermanState.{code}: [")
        for start, end, kind in sorted(periods[code]):
            lines.append(
                f"    SchoolHolidayPeriod({date(start)}, {date(end)}, "
                f"SchoolHolidayKind.{kind}),"
            )
        lines.append("  ],")
    lines.append("};")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{sum(len(v) for v in periods.values())} periods for {len(periods)} states")


if __name__ == "__main__":
    main()
